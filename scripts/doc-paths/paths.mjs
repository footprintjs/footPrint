/**
 * paths.mjs: the one rule for "a repo path named in a doc exists". Pure functions, no I/O.
 *
 * A doc names a repo path when a token starts with one of `ROOTS` followed by `/`. The token is
 * checked against the tracked tree: a tracked file, a tracked folder, or a tracked file with an
 * extension the doc left out. A path written from the doc's own package (a doc under `docs-site/`
 * naming `src/env.d.ts`) is tried against that package's folder after the repo root.
 */
import { dirname, posix } from 'node:path';

/** The first segment of every path the check reads. Anything else is prose, a package name or a URL. */
export const ROOTS = Object.freeze([
  'src',
  'test',
  'docs',
  'docs-site',
  'scripts',
  'examples',
  'bench',
  'ai-instructions',
  'contract',
  '.github',
  '.claude',
]);

/** Docs the check does not read. Each one says why. */
export const EXCLUDED_DOCS = Object.freeze([
  { test: (file) => file === 'CHANGELOG.md', why: 'history: each entry names the tree of its own release' },
  {
    test: (file) => file.startsWith('docs/design/'),
    why: 'dated design notes: they describe the tree they were written in',
  },
  {
    test: (file) => file === 'bench/agent-debug/twin/BRIEF.md',
    why: "a verbatim record of the messages the twin's blind writer received: its paths name that writer's own folder, and the record is kept unedited (bench/agent-debug/RULE-2.md)",
  },
  {
    test: (file) => file === 'bench/agent-debug/twin-proof/FAIRNESS-READING-1.md',
    why: "a verbatim record of the independent fairness reader's report: its paths name the reader's own scripts and either program's files as each program holds them, and the record is kept unedited (bench/agent-debug/RULE-2.md)",
  },
]);

/** Paths a doc may name that are not in this repository's tree. Each one says why. */
export const ALLOWED_PATHS = Object.freeze([
  {
    path: '.claude/skills/footprint/SKILL.md',
    why: "install destination in a user's project (ai-instructions/README.md)",
  },
  {
    path: '.github/copilot-instructions.md',
    why: "install destination in a user's project (ai-instructions/README.md)",
  },
  { path: 'docs-site/dist', why: 'generated by the site build, ignored by git' },
  { path: 'bench/results/latest.json', why: 'written by a bench run, ignored by git' },
]);

/**
 * Packages whose own tree a doc may describe. A sentence that names one speaks about that
 * repository, so its paths are not checked here (the `foottrace` package owns the record's files).
 */
export const FOREIGN_PACKAGES = Object.freeze(['foottrace']);

const PATH_CHARS = '[A-Za-z0-9_@.\\-/\\[\\]*{},]+';
const pathPattern = () => new RegExp(`(?<![\\w@/.$-])((?:${ROOTS.map(escape).join('|')})/${PATH_CHARS})`, 'g');
const foreignPattern = new RegExp(`\\b(?:${FOREIGN_PACKAGES.map(escape).join('|')})\\b`);
const SENTENCE_END = /[.!?](?=\s)/g;

function escape(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** What the tracked tree holds: files, folders, files by name without extension, and package roots. */
export function indexTree(trackedFiles) {
  const files = new Set(trackedFiles);
  const folders = new Set();
  const stems = new Set();
  const packages = [];
  for (const file of trackedFiles) {
    for (let folder = posix.dirname(file); folder !== '.' && !folders.has(folder); folder = posix.dirname(folder))
      folders.add(folder);
    const extension = posix.extname(file);
    if (extension) stems.add(file.slice(0, -extension.length));
    if (posix.basename(file) === 'package.json' && file !== 'package.json') packages.push(posix.dirname(file));
  }
  return { files, folders, stems, packages };
}

/**
 * The token as a path: no trailing punctuation, no `:line` suffix, no trailing slash. `undefined` for a
 * glob or a placeholder (`src/lib/*.ts`, `src/{a,b}`, `src/...`). A placeholder such as `src/<name>` ends
 * the token at `<`, so only its real part (`src`) is checked.
 */
export function cleanPath(token) {
  if (/[*{}[\]]|\.\.\./.test(token)) return undefined;
  let path = token.replace(/[.,;:)\]]+$/, '').replace(/:\d+(?:-\d+)?$/, '');
  path = path.replace(/\/+$/, '');
  return posix.normalize(path);
}

function existsIn(index, path) {
  return index.files.has(path) || index.folders.has(path) || index.stems.has(path);
}

function allowed(path) {
  return ALLOWED_PATHS.some((entry) => path === entry.path || path.startsWith(`${entry.path}/`));
}

/** The doc's package folder: the nearest folder above it with its own `package.json`, or `undefined`. */
function packageOf(index, file) {
  const folder = dirname(file);
  return index.packages
    .filter((root) => folder === root || folder.startsWith(`${root}/`))
    .sort((a, b) => b.length - a.length)[0];
}

/** True when the path is in the tree, read from the repo root, then from the doc's package folder. */
export function resolves(index, file, path) {
  if (allowed(path) || existsIn(index, path)) return true;
  const root = packageOf(index, file);
  return root !== undefined && existsIn(index, posix.join(root, path));
}

/** Every paragraph's text with the line each one starts on. A paragraph is a run of non-blank lines. */
function paragraphs(text) {
  const out = [];
  let lines = [];
  let start = 0;
  text.split('\n').forEach((line, i) => {
    if (line.trim() === '') {
      if (lines.length) out.push({ text: lines.join('\n'), line: start });
      lines = [];
      return;
    }
    if (!lines.length) start = i + 1;
    lines.push(line);
  });
  if (lines.length) out.push({ text: lines.join('\n'), line: start });
  return out;
}

/** The sentence around [from, to): from the last sentence end before it to the first one after it. */
function sentenceAround(text, from, to) {
  let start = 0;
  let end = text.length;
  for (const match of text.matchAll(SENTENCE_END)) {
    if (match.index < from) start = match.index + 1;
    else if (match.index >= to) {
      end = match.index;
      break;
    }
  }
  return text.slice(start, end);
}

/** True when the sentence names a foreign package, outside the paths it names. */
function speaksOfForeignPackage(sentence) {
  return foreignPattern.test(sentence.replace(pathPattern(), ''));
}

/** Every repo path the doc names, with its line, except globs, placeholders and paths in a foreign package's sentence. */
export function pathsIn(text) {
  const out = [];
  for (const paragraph of paragraphs(text)) {
    for (const match of paragraph.text.matchAll(pathPattern())) {
      const path = cleanPath(match[1]);
      if (path === undefined) continue;
      if (speaksOfForeignPackage(sentenceAround(paragraph.text, match.index, match.index + match[1].length))) continue;
      const line = paragraph.line + paragraph.text.slice(0, match.index).split('\n').length - 1;
      out.push({ line, path });
    }
  }
  return out;
}

/** True when the check does not read this doc. */
export function excluded(file) {
  return EXCLUDED_DOCS.some((entry) => entry.test(file));
}

/** Whether the check reads this tracked file at all: a Markdown or MDX doc that is not excluded. */
export function isDoc(file) {
  return /\.mdx?$/.test(file) && !excluded(file);
}

/** One doc's problems: each `{ file, line, path }` it names that the tree does not hold. */
export function docProblems(index, file, text) {
  if (!isDoc(file)) return [];
  return pathsIn(text)
    .filter(({ path }) => !resolves(index, file, path))
    .map(({ line, path }) => ({ file, line, path }));
}

/** Every problem in the tracked tree. `readDoc(file)` returns a doc's text. */
export function findProblems(trackedFiles, readDoc) {
  const index = indexTree(trackedFiles);
  return trackedFiles.filter(isDoc).flatMap((file) => docProblems(index, file, readDoc(file)));
}

/** The one line a problem prints. */
export const formatProblem = ({ file, line, path }) => `${file}:${line}: ${path}`;
