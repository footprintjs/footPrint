/**
 * The report, from a fixed `runs.jsonl` (test/fixtures/runs.jsonl), to
 * RULE.md version 1.2: the decision first, the transcripts a reviewer must
 * read (never the word "void"), the four groups, every fault by itself and
 * the context at the end of a run.
 *
 * The fixture: fault `a` is a decision fault, `b` another data-flow fault,
 * `c` a control. Set-up 1 solves 2 of 3 data-flow runs with 300,000 tokens
 * (150,000 per solved task); set-up 3 solves 3 of 3 with 120,000 (40,000);
 * on the control both solve 1 of 2.
 */
import assert from 'node:assert/strict';
import { join } from 'node:path';
import { test } from 'node:test';

import { readRuns } from '../harness/batch.mjs';
import { decision, groups, renderReport, sensitivity, summarize, transcriptsToRead } from '../harness/report.mjs';
import { BENCH_DIR } from '../harness/runtime.mjs';

const runs = readRuns(join(BENCH_DIR, 'test', 'fixtures', 'runs.jsonl'));
const planOf = (rows) => rows.map((r) => ({ setup: r.setup, fault: r.fault, repeat: r.repeat }));
const plan = planOf(runs);

test('tokens per solved task counts every run and divides by the solved ones', () => {
  const one = summarize(runs.filter((r) => r.setup === 1 && r.faultClass === 'data-flow'));
  assert.deepEqual([one.runs, one.solved, one.tokens, one.tokensPerSolved], [3, 2, 300_000, 150_000]);
  assert.equal(one.meanFinalContext, 70_000 / 3);
  const g = groups(runs.filter((r) => r.setup === 3));
  assert.equal(g.dataFlow.tokensPerSolved, 40_000);
  assert.deepEqual([g.decision.runs, g.otherFour.runs, g.controls.runs], [2, 1, 2]);
  assert.equal(summarize([]).tokensPerSolved, null);
});

test('the report puts the decision first and lists the transcripts to read', () => {
  const md = renderReport(runs, { title: 'fixed', plan });
  assert.match(md, /^# fixed\n\nGenerated by .*\n\n## The decision \(RULE\.md\)\n\nGo on to the full study: on the seven data-flow faults set-up 3 solved 3 of 3 \(100%\) of its finished runs against set-up 1's 2 of 3 \(67%\) \(73% fewer tokens per solved task\), and with any one fault and each set-up's most expensive run left out set-up 3 still solves as large a share and uses at least 15% fewer tokens per solved task\./);
  assert.ok(!/\bvoid\b/i.test(md.replace(/Whether the batch is void is a reviewer's finding/, '')), 'the report never declares a batch void');
  assert.deepEqual(transcriptsToRead(runs), ['transcripts/setup3-a-r1.jsonl', 'transcripts/setup3-a-r2.jsonl', 'transcripts/setup3-c-r1.jsonl']);
  assert.match(md, /Transcripts to read \(3\):\n- `transcripts\/setup3-a-r1\.jsonl`/);
  assert.match(md, /\| 1 \| 7 data-flow \| 3 \| 2 \| 300,000 \| 150,000 \| 23,333 \|/);
  assert.match(md, /\| 3 \| 3 decision \(of the 7\) \| 2 \| 2 \| 80,000 \| 40,000 \| 9,000 \|/);
  assert.match(md, /\| 3 \| 4 other data-flow \(of the 7\) \| 1 \| 1 \| 40,000 \| 40,000 \| 9,000 \|/);
  assert.match(md, /\| a \| data-flow, decision \| 1 \| 2 of 2 \| 100,000 \| 10\.0 \|/);
  assert.match(md, /\| b \| data-flow \| 1 \| 0 of 1 \| none solved \| 10\.0 \|/);
  assert.match(md, /\| c \| control \| 3 \| 1 of 2 \| 100,000 \| 10\.0 \|/);
  assert.match(md, /\| 1 \| 5 or more \| 1 \| 0 \| none solved \|/);
});

const g = (df, other, controls = { solved: 1, tokensPerSolved: 1 }) => ({ dataFlow: df, decision: df, otherFour: other, controls });
/** A sensitivity table that holds in every row. */
const OK_ROWS = [{ label: 'x', holds: true }];
const s = (solved, tokensPerSolved, runs = 6) => ({ solved, tokensPerSolved, runs });

test('the decision: go on, go on only through the decision faults, stop and look', () => {
  assert.match(decision({ 1: g(s(5, 100), s(2, 100)), 3: g(s(5, 75), s(2, 90)) }, OK_ROWS), /^Go on to the full study: [^]*\.$/);
  assert.ok(!decision({ 1: g(s(5, 100), s(2, 100)), 3: g(s(5, 75), s(2, 90)) }, OK_ROWS).includes('only because'));
  const onlyDecision = decision({ 1: g(s(5, 100), s(2, 100)), 3: g(s(5, 70), s(2, 120)) }, OK_ROWS);
  assert.match(onlyDecision, /^Go on to the full study: .* This holds only because of the three decision faults: on the other four, set-up 3 is not cheaper than set-up 1 \(120 against 100 tokens per solved task\), so the full study must use programs whose faults lie mostly outside decisions\.$/);
  assert.match(decision({ 1: g(s(5, 100), s(2, 100)), 3: g(s(5, 70), s(0, null)) }, OK_ROWS), /only because of the three decision faults/);
  assert.match(decision({ 1: g(s(5, 100), s(2, 100)), 3: g(s(5, 76), s(2, 50)) }, OK_ROWS), /^Stop and look: .*not at least 25% cheaper/);
  assert.match(decision({ 1: g(s(6, 100), s(2, 100)), 3: g(s(5, 10), s(2, 10)) }, OK_ROWS), /^Stop and look: .*it solved a smaller share/);
  assert.match(decision({ 1: g(s(0, null), s(0, null)), 3: g(s(1, 50), s(1, 50)) }, OK_ROWS), /^Go on/);
  assert.match(decision({ 1: g(s(0, null), s(0, null)) }, OK_ROWS), /^No decision/);
  for (const text of [onlyDecision, decision({ 1: g(s(5, 100), s(2, 100), s(0, null)), 3: g(s(5, 70), s(2, 50), s(3, 1)) }, OK_ROWS)]) {
    assert.ok(!/void/i.test(text));
  }
});

const row = (setup, fault, inDecision, solved, tokens, repeat = 1, stopReason) => ({
  setup, fault, faultClass: 'data-flow', inDecision, distance: 2, repeat, solved, inputTokens: tokens, outputTokens: 0, requests: 5,
  finalContextTokens: 1, stopReason: stopReason ?? (solved ? 'done' : 'max_requests'), model: 'm', transcript: `t/${setup}-${fault}-${repeat}`,
});

test('the reader\'s case A: a partial batch gives no decision', () => {
  const a = [];
  for (let r = 1; r <= 3; r++) a.push(row(1, `f${r}`, false, true, 40000));
  for (let r = 1; r <= 9; r++) a.push(row(3, `f${r % 7}`, r % 2 === 0, r <= 3, 1000, r));
  const fullPlan = [1, 3].flatMap((setup) => Array.from({ length: 7 }, (_, f) => [1, 2, 3].map((repeat) => ({ setup, fault: `f${f}`, repeat }))).flat());
  assert.match(renderReport(a, { plan: fullPlan }), /## The decision \(RULE\.md\)\n\nNo decision: \d+ of the 42 planned runs are missing/);
  assert.match(renderReport(a), /No decision: there is no plan/);
});

test('the reader\'s case B: one failed set-up 1 run at 450,000 tokens no longer gives go', () => {
  const b = [];
  for (let i = 0; i < 21; i++) {
    const fault = `f${i % 7}`;
    const repeat = Math.floor(i / 7) + 1;
    b.push(row(3, fault, i % 7 < 3, true, 30000, repeat));
    b.push(row(1, fault, i % 7 < 3, i !== 0, i === 0 ? 450000 : 30000, repeat));
  }
  const rows = sensitivity(b);
  const priciest = rows.find((r) => r.label.startsWith('the most expensive run'));
  assert.equal(priciest.holds, false);
  const text = decision({ 1: groups(b.filter((r) => r.setup === 1)), 3: groups(b.filter((r) => r.setup === 3)) }, rows);
  assert.match(text, /^Stop and look: .*but the result hangs on one fault or one run: with fault f0 left out, .*; with the most expensive run of each set-up left out, set-up 3 solves 20 of 20 \(100%\) against 20 of 20 \(100%\) at 30,000 against 30,000 tokens per solved task\. Read/);
  assert.ok(!text.startsWith('Go'));
  const md = renderReport(b, { plan: planOf(b) });
  assert.match(md, /\| the most expensive run of each set-up left out \| 20 of 20 \(100%\) \| 30,000 \| 20 of 20 \(100%\) \| 30,000 \| 0% \| no \|/);
});

test('error and interrupted runs are left out of every number, listed, and withhold a decision past three', () => {
  const base = [];
  for (const setup of [1, 3]) for (let f = 0; f < 7; f++) base.push(row(setup, `f${f}`, f < 3, true, setup === 1 ? 50000 : 10000));
  const unfinished = [row(3, 'f0', true, false, 999999, 2, 'error'), row(1, 'f1', false, false, 777777, 2, 'interrupted')];
  const all = [...base, ...unfinished];
  const md = renderReport(all, { plan: planOf(all) });
  assert.match(md, /^Go on/m);
  assert.ok(!md.includes('999,999') && !md.includes('777,777'), 'their tokens are in no number');
  assert.match(md, /Runs the harness could not finish \(kept, counted in the spend, left out of every number\): `t\/3-f0-2` \(error\), `t\/1-f1-2` \(interrupted\)\./);
  assert.match(md, /\| 1 \| 7 data-flow \| 7 \| 7 \|/);
  const many = [...all, row(1, 'f2', false, false, 1, 2, 'error'), row(1, 'f3', false, false, 1, 2, 'error')];
  assert.match(renderReport(many, { plan: planOf(many) }), /No decision: 4 runs ended as error or interrupted, more than 3/);
});

test('a smoke report never prints a decision', () => {
  const smoke = [row(1, 'wrong-key-read', false, true, 100), row(2, 'wrong-key-read', false, true, 100), row(3, 'wrong-key-read', false, true, 10)];
  const md = renderReport(smoke, { plan: planOf(smoke), smoke: true });
  assert.match(md, /No decision: a smoke batch is not part of the result and decides nothing/);
  assert.ok(!/Go on to the full study|Stop and look/.test(md));
});

test('the reader\'s cases 4 and 5: rows twice, or a row outside the plan, give no decision (RULE 1.4)', () => {
  const base = [];
  for (const setup of [1, 3]) for (let f = 0; f < 7; f++) base.push(row(setup, `f${f}`, f < 3, true, setup === 1 ? 50000 : 10000));
  const plan = planOf(base);
  assert.match(renderReport(base, { plan }), /\n\nGo on/);
  assert.match(renderReport([...base, ...base], { plan }), /No decision: 14 planned runs appear more than once/);
  assert.match(renderReport([...base, row(3, 'f0', true, true, 1, 4)], { plan }), /No decision: 1 rows are not in the plan \(3\/f0\/4\)/);
});

test('RULE 1.4: a left-out row needs 15% fewer tokens, and shares (not counts) decide', () => {
  // The reader's case 1: one fault carries the result; without it set-up 3 is only 3% cheaper.
  const c1 = [];
  for (const setup of [1, 3]) for (let f = 0; f < 7; f++) for (let r = 1; r <= 3; r++) {
    const tokens = setup === 1 ? (f === 0 ? 300000 : 30000) : 29000;
    c1.push(row(setup, `f${f}`, f < 3, true, tokens, r));
  }
  const md1 = renderReport(c1, { plan: planOf(c1) });
  assert.match(md1, /\n\nStop and look: .*with fault f0 left out, set-up 3 solves 18 of 18 \(100%\) against 18 of 18 \(100%\) at 29,000 against 30,000/);
  assert.match(md1, /\| fault f0 left out \| 18 of 18 \(100%\) \| 30,000 \| 18 of 18 \(100%\) \| 29,000 \| 3% \| no \|/);
  // The reader's case 6: three unfinished set-up 1 runs; counts 21 against 18 would mislead, shares do not.
  const c6 = [];
  for (const setup of [1, 3]) for (let f = 0; f < 7; f++) for (let r = 1; r <= 3; r++) {
    const unfinished = setup === 1 && f === 6;
    c6.push(row(setup, `f${f}`, f < 3, !unfinished, setup === 3 ? 20000 : 30000, r, unfinished ? 'interrupted' : undefined));
  }
  assert.match(renderReport(c6, { plan: planOf(c6) }), /set-up 3 solved 21 of 21 \(100%\) of its finished runs against set-up 1's 18 of 18 \(100%\)/);
  // A smaller share for set-up 3 is never "go", however cheap.
  assert.match(decision({ 1: g(s(6, 100, 6), s(2, 100, 2)), 3: g(s(6, 10, 7), s(2, 10, 2)) }, OK_ROWS), /^Stop and look: .*it solved a smaller share/);
});

test('a smoke report prints no sensitivity table', () => {
  const smoke = [row(1, 'wrong-key-read', false, true, 100), row(3, 'wrong-key-read', false, true, 10)];
  assert.ok(!renderReport(smoke, { plan: planOf(smoke), smoke: true }).includes('Does the result hang'));
});
