/**
 * Reads `runs.jsonl` and writes `report.md`. Every number in the report is
 * computed here from the run lines; none is typed by hand (RULE.md, rule 3).
 *
 * Headline (RULE.md): tokens per solved task = all input and output tokens
 * of all runs of a set-up, solved or not, divided by its solved runs;
 * reported for the seven data-flow faults and the three controls apart.
 * Example: `node harness/report.mjs <folder>` → `<folder>/report.md`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { costOf } from './budget.mjs';
import { readRuns } from './batch.mjs';

/** @param {any[]} runs */
export function summarize(runs) {
  const tokens = runs.reduce((s, r) => s + r.inputTokens + r.outputTokens, 0);
  const solved = runs.filter((r) => r.solved).length;
  return {
    runs: runs.length,
    solved,
    tokens,
    tokensPerSolved: solved > 0 ? tokens / solved : null,
    meanRequests: runs.length ? runs.reduce((s, r) => s + r.requests, 0) / runs.length : null,
    namedStep: runs.filter((r) => r.namedFaultyStep).length,
    editedFaultyFile: runs.filter((r) => r.editedFaultyFile).length,
  };
}

const band = (d) => (d <= 1 ? '0 to 1' : d <= 4 ? '2 to 4' : '5 or more');
const fmt = (n) => (n === null ? 'none solved' : Math.round(n).toLocaleString('en-US'));

/**
 * RULE.md, "What decides the next step", read off the numbers.
 * @param {Record<number, { dataFlow: any, controls: any }>} bySetup
 */
export function decision(bySetup) {
  const one = bySetup[1];
  const three = bySetup[3];
  if (!one || !three) return 'No decision: the batch does not hold both set-up 1 and set-up 3.';
  const controlEdge = three.controls.solved - one.controls.solved;
  if (controlEdge > 1) {
    return `Void: on the three controls set-up 3 solved ${three.controls.solved} runs against set-up 1's ${one.controls.solved}, an advantage beyond one run, so the harness may be leaking the answer.`;
  }
  const solvesEnough = three.dataFlow.solved >= one.dataFlow.solved;
  const cheaper =
    three.dataFlow.tokensPerSolved !== null &&
    (one.dataFlow.tokensPerSolved === null || three.dataFlow.tokensPerSolved <= 0.75 * one.dataFlow.tokensPerSolved);
  const ratio =
    three.dataFlow.tokensPerSolved !== null && one.dataFlow.tokensPerSolved !== null
      ? ` (${Math.round((1 - three.dataFlow.tokensPerSolved / one.dataFlow.tokensPerSolved) * 100)}% fewer tokens per solved task)`
      : '';
  if (solvesEnough && cheaper) {
    return `Go on to the full study: on the seven data-flow faults set-up 3 solved ${three.dataFlow.solved} runs against set-up 1's ${one.dataFlow.solved}${ratio}, and its advantage on the controls is ${controlEdge} run(s). Read the transcripts for a tool handing over the answer before relying on this.`;
  }
  return `Stop and look: on the seven data-flow faults set-up 3 solved ${three.dataFlow.solved} runs against set-up 1's ${one.dataFlow.solved}${ratio}; ${solvesEnough ? 'it is not at least 25% cheaper per solved task' : 'it solved fewer'}. Read the transcripts and say why before building anything else.`;
}

/** @param {any[]} runs @param {{ title?: string }} [options] */
export function renderReport(runs, options = {}) {
  const setups = [...new Set(runs.map((r) => r.setup))].sort();
  /** @type {Record<number, { dataFlow: any, controls: any }>} */
  const bySetup = {};
  for (const s of setups) {
    const mine = runs.filter((r) => r.setup === s);
    bySetup[s] = { dataFlow: summarize(mine.filter((r) => r.faultClass === 'data-flow')), controls: summarize(mine.filter((r) => r.faultClass === 'inside-step')) };
  }
  const models = [...new Set(runs.map((r) => r.model))].join(', ');
  const spend = runs.reduce((s, r) => s + costOf({ input_tokens: r.inputTokens, output_tokens: r.outputTokens }), 0);
  const lines = [
    `# ${options.title ?? 'agent-debug report'}`,
    '',
    `Generated by \`harness/report.mjs\` from \`runs.jsonl\`: ${runs.length} runs, model ${models}, spend estimate ${spend.toFixed(4)} dollars at RULE.md's prices. No number here is typed by hand.`,
    '',
    '## Tokens per solved task',
    '',
    'All input and output tokens of all runs of a set-up, solved or not, divided by its solved runs.',
    '',
    '| Set-up | Faults | Runs | Solved | Tokens | Tokens per solved task | Mean requests | Named the faulty step | Edited the faulty file |',
    '|---|---|---|---|---|---|---|---|---|',
  ];
  for (const s of setups) {
    for (const [label, sum] of [['7 data-flow', bySetup[s].dataFlow], ['3 controls', bySetup[s].controls]]) {
      lines.push(`| ${s} | ${label} | ${sum.runs} | ${sum.solved} | ${fmt(sum.tokens)} | ${fmt(sum.tokensPerSolved)} | ${sum.meanRequests === null ? '-' : sum.meanRequests.toFixed(1)} | ${sum.namedStep} | ${sum.editedFaultyFile} |`);
    }
  }
  lines.push('', '## By distance (data-flow faults)', '', '| Set-up | Distance | Runs | Solved | Tokens per solved task |', '|---|---|---|---|---|');
  for (const s of setups) {
    for (const b of ['0 to 1', '2 to 4', '5 or more']) {
      const sum = summarize(runs.filter((r) => r.setup === s && r.faultClass === 'data-flow' && band(r.distance) === b));
      lines.push(`| ${s} | ${b} | ${sum.runs} | ${sum.solved} | ${fmt(sum.tokensPerSolved)} |`);
    }
  }
  lines.push('', '## Stop reasons', '', '| Set-up | Stop reason | Runs |', '|---|---|---|');
  for (const s of setups) {
    const counts = {};
    for (const r of runs.filter((x) => x.setup === s)) counts[r.stopReason] = (counts[r.stopReason] ?? 0) + 1;
    for (const [reason, n] of Object.entries(counts).sort()) lines.push(`| ${s} | ${reason} | ${n} |`);
  }
  lines.push('', '## The decision (RULE.md)', '', decision(bySetup));
  if (bySetup[2] && bySetup[1]) {
    const two = bySetup[2].dataFlow;
    const one = bySetup[1].dataFlow;
    lines.push('', `Set-up 2 against set-up 1 (decides nothing): on the data-flow faults set-up 2 solved ${two.solved} runs at ${fmt(two.tokensPerSolved)} tokens per solved task, set-up 1 ${one.solved} at ${fmt(one.tokensPerSolved)}.`);
  }
  return `${lines.join('\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const folder = process.argv[2];
  if (!folder) {
    console.error('usage: node harness/report.mjs <folder holding runs.jsonl>');
    process.exit(2);
  }
  const title = process.argv[3];
  writeFileSync(join(folder, 'report.md'), renderReport(readRuns(join(folder, 'runs.jsonl')), title ? { title } : {}));
  console.log(readFileSync(join(folder, 'report.md'), 'utf8'));
}
