/** Snapshot of a single recorder's collected data. */
export interface RecorderSnapshot {
  id: string;
  name: string;
  /** ScopeRecorder type and pattern description (e.g., "Translator (KeyedStore) — per-step token usage"). */
  description?: string;
  /** Preferred read-time operation — hints the UI about which view to show prominently. */
  preferredOperation?: 'translate' | 'accumulate' | 'aggregate';
  data: unknown;
  /**
   * Small machine-readable facts about the BUNDLE — how it was produced,
   * which projection of the recorder's data it is, what it deliberately
   * left out. Whatever the recorder's `toSnapshot()` put here, copied
   * through unchanged.
   *
   * The split with `description`: `description` is the sentence a human
   * reads; `meta` is what an offline consumer BRANCHES on. A recorder with
   * a "full" and a "lean" bundle shape that says so only in its
   * description forces every reader to string-match prose — and a reader
   * that doesn't renders an empty panel instead of saying "this recording
   * carries structure only".
   *
   * Not interpreted by the engine, so keys are the recorder's to choose;
   * keep the values JSON-safe, since this rides the snapshot out to disk.
   */
  meta?: Readonly<Record<string, unknown>>;
  /** Optional current-run capture acknowledgement from the recorder contract. */
  capture?: RecorderCaptureAcknowledgement;
}

export type RuntimeSnapshot = {
  /** Present only when resume-prefix evidence was requested on a resumed traversal. */
  readonly resumePrefixGap?: 'resume-prefix-unavailable';
  /** Historical child evidence was withheld because disclosure could not be verified. */
  subflowEvidenceGap?: 'retained-child-evidence-withheld';
  /**
   * The run this snapshot belongs to — the same `runId` stamped on every
   * `TraversalContext` (and thus every recorder event) of the run, so a
   * snapshot can be joined against an event stream or an external
   * correlation table. Read-only by contract: generated by the executor
   * (`runner/runId.ts`), never derived from snapshot contents.
   *
   * Lifecycle (matches the event model): fresh per `run()` AND per
   * `resume()` — resume is logically a distinct run, so a post-resume
   * snapshot carries a DIFFERENT runId than the paused run's snapshot.
   */
  readonly runId: string;
  /** Opt-in current-leg evidence, never a durable storage receipt. */
  readonly capture?: NativeCaptureObservation | ExplainCaptureNote;
  /** Opt-in native work counts; terminal unverified observations never authorize complete capture. */
  readonly captureExtent?: NativeCaptureExtent;
  /** Opt-in ordered native occurrences. Unknown ownership has no record; never infer observed-empty. */
  readonly readSources?: EngineReadSources;
  /**
   * The run's correlation (10.1) — `env.traceparent`, or `env.traceId` + `env.operationId`, resolved once per
   * leg; the same frozen object every event of the leg carries (`TraversalContext.correlation`, a scope event's
   * `correlation`). Like `runId`, per leg: a resume carries ITS env's, never the paused leg's. Absent — no
   * key — when none was given.
   */
  readonly correlation?: RunCorrelation;
  sharedState: Record<string, unknown>;
  executionTree: StageSnapshot;
  /**
   * The commit log's fold BASE — the run's state before its first commit
   * (`initialContext` merged with `defaultValuesForContext`; on a resume, the
   * checkpoint's state). Deeply frozen and fully detached from the engine.
   *
   * Commit bundles are DIFFS, so the log alone cannot rebuild a value that
   * was seeded before the run and only ever merged afterwards. Shipping the
   * base WITH the log is what makes an offline fold — `stateAt(snapshot, i)`
   * from `foottrace` — reproduce the state a stage actually saw.
   *
   * `getSnapshot({ redact: true })` serves it through the current native state
   * rule, including marks inherited during the run. The raw view is unchanged.
   * Optional by type for older recordings and consumer-constructed snapshots;
   * `stateAt` reports `basis: 'log-only'` when that older base is absent.
   */
  readonly initialState?: Record<string, unknown>;
  /**
   * The run's commit bundles, one per executed stage, in execution order —
   * a DETACHED, frozen copy of the engine's live log (a snapshot is a fold
   * result: it must not keep changing under the consumer that holds it).
   * The bundles inside are the engine's own objects, immutable after record.
   */
  commitLog: CommitBundle[];
  /** Identity of this log, stable across same-executor resume. Absent before binding or in older sources. */
  readonly logAddress?: LogAddress;
  /** Present only when child-output handoff observation was explicitly requested. */
  readonly captureOutputHandoff?: true;
  /** Bounded parent-owned scope observations, not an invocation completeness certificate. */
  readonly fanoutCollections?: FanoutCollections;
  /** Present only when built-in TypedScope nested member observation was requested. */
  readonly nestedReadTracking?: true;
  /**
   * Encoding discriminant for `commitLog` (#13c-B): `'full'` — every `set`
   * bundle stores the full final value (historical); `'delta'` — bundles may
   * carry `append`/`delete` trace verbs with verb-qualified `overwrite`
   * payloads (tails). Offline tooling keys on this field; a bundle stream
   * without context remains self-describing via the verbs themselves.
   */
  commitValues: CommitValuesMode;
  /** Per-write read-provenance dial (#P1) the run executed under — the
   *  offline-tooling discriminant for `TraceEntry.readKeys` availability. */
  writeProvenance: WriteProvenanceMode;
  /**
   * Per-subflow execution results, DUAL-KEYED (design: docs/design/subflow-commit-visibility.md):
   *   - by subflow PATH (`subflowId`, e.g. `'sf-pay'`) → the LAST iteration (back-compat); this
   *     is what `getSubtreeSnapshot(path)` and `listSubflowPaths()` resolve.
   *   - by per-execution mount `runtimeStageId` (e.g. `'sf-pay#5'`) → THAT iteration's result, so
   *     a LOOPING subflow retains EVERY iteration (not just the last). Look up a specific
   *     iteration as `subflowResults[node.runtimeStageId] ?? subflowResults[node.subflowId]`.
   * Both keys point at the same object for a single mount; iterate with care (count via the
   * path keys — those without `'#'`). The pause checkpoint carries only the path keys, lean.
   *
   * Under `getSnapshot({ redact: true })` each entry's `treeContext.globalContext` is that
   * subflow's OWN redacted mirror (9.20.0) — the fold of its scrubbed `history` — served as
   * one substituted object per mount (both keys still agree) — the wrapper is fresh per
   * `getSnapshot` call, the `globalContext` inside it is the stable mirror; plain, it is the subflow's
   * live heap. Without a policy there is no mirror and the two views are the same objects.
   */
  subflowResults?: Record<string, unknown>;
  /** Snapshot data from recorders that implement toSnapshot(). */
  recorders?: RecorderSnapshot[];
  /**
   * Deferred-observer accounting (RFC-001 Block 9) — queue depth, drops,
   * flush/budget counters, per-listener time attribution, and the
   * terminal-flush stranding count. ABSENT unless a recorder was attached
   * with `{ delivery: 'deferred' }` on this executor (zero-cost discipline).
   */
  observerStats?: ObserverStats;
  /**
   * The crash-safe record's accounting (10.1, P6) — how many entries the run handed its sink and how many the sink
   * did not take. ABSENT unless the executor was built with a `sink` and a run started.
   */
  sink?: RecordSinkStats;
};

/**
 * Where a runtime's log writes as it lands (10.1, P6): the run's sink, the log's address and what the writer puts on
 * its `opened` entry. Absent → the log is the plain one-argument `EventLog`, byte-identical to 10.0.
 */
export interface RuntimeRecord {
  readonly sink: RecordSink;
  readonly address: LogAddress;
  readonly meta?: Meta;
  readonly collects?: Pick<LogCollects, 'reads'>;
}

export class ExecutionRuntime {
  /** Installed only for explicit handoff capture. It is not the app's persistence sink. */
  private declare handoffCommitTap?: CommitTap;

  /** The most recent bundle as it landed, for immediate exact-index handoff admission. */
  lastHandoffCommit(): CommitBundle | undefined {
    return this.handoffCommitTap?.last();
  }

  /** @internal Current native leg's runtime bank; each scope captures its own stage view. */
  runFrame?: RunFrame;
  readSources?: EngineReadSourceCapture;
  /** Current native log and leg. A mounted child begins its own v3 observation. */
  capture?: NativeCapture;
  declare captureExtent?: NativeExtent;

  beginCapture(runId: string, extent = false, explanation?: ExplainCaptureFactory): NativeCapture {
    const address = this.executionHistory.address ?? this.capture?.logAddress ?? { logRunId: runId, drillPath: [] };
    if (explanation && !this.executionHistory.address)
      this.executionHistory.bindAddress(address.logRunId, address.drillPath);
    const capture = new NativeCapture(runId, address, this.executionHistory.length, this.policy);
    if (explanation) {
      const handoff = subflowCaptureFor(this.policy);
      capture.explanation = explanation({
        nestedReads: this.policy.nestedReadTracking,
        readSources: !!this.policy.readSources,
        inputHandoff: handoff?.input === true,
        outputHandoff: this.policy.captureOutputHandoff,
        fanoutHandoff: handoff?.fanout === true,
      });
    }
    if (this.capture) capture.limit('resumed-segment');
    this.capture = capture;
    this.rootStageContext.capture = capture;
    if (extent) {
      this.captureExtent = new NativeExtent(runId, address, this.executionHistory.length);
      this.rootStageContext.captureExtent = this.captureExtent;
    } else if (this.captureExtent) {
      delete this.captureExtent;
      delete this.rootStageContext.captureExtent;
    }
    return capture;
  }

  /** A reused log cannot be retrofitted or relabelled as the new leg's base. */
  resumeReadSources(runId: string): void {
    subflowCaptureFor(this.policy)?.reset(this);
    this.readSources?.retire();
    this.readSources = this.policy.readSources
      ? new EngineReadSourceCapture(runId, undefined, 'resumed-source-ownership', this.executionHistory.length)
      : undefined;
    this.rootStageContext.readSources = this.readSources;
  }

  captureSnapshot(
    to: number,
    control: CaptureChannelStatus = 'unknown',
    redact = false,
  ): NativeCaptureObservation | undefined {
    const note = this.capture?.snapshot(to, control, redact);
    return note && this.readSources ? withReadSources(note, this.readSources.snapshot(to, redact)) : note;
  }

  /** The v3 wire note is a served memory view. Stored capture and checkpoints keep their strict codecs. */
  explainSnapshot(control: CaptureChannelStatus = 'unknown', redact = false): ExplainCaptureNote | undefined {
    const capture = this.capture;
    if (!capture?.explanation) return undefined;
    const rule = this.policy.redaction;
    if (redact && hidesExplainIdentity(rule, capture.runId, capture.logAddress)) return undefined;
    const to = this.executionHistory.length;
    const note = capture.snapshot(to, control);
    return capture.explanation.snapshot(
      note,
      this.readSources?.snapshot(to),
      subflowCaptureFor(this.policy)?.view(this, false),
      control,
      {
        redact,
        activePrivacy: rule?.isInert() === false,
        hideFailureStage: redact && hidesExplainFailureStage(rule, note.boundary.failure?.stage),
      },
    );
  }

  finishChildExplanation(
    status: 'completed' | 'paused' | 'failed' | 'cancelled',
    broken = false,
    error?: unknown,
  ): void {
    if (!this.capture?.explanation) return;
    if (broken) this.capture.limit('execution-broken');
    const failure =
      status === 'failed' || status === 'cancelled' ? this.rootStageContext.failureState.announce(error) : undefined;
    this.capture.end(status, failure);
  }

  public globalStore: SharedMemory;
  /**
   * Parallel redacted mirror of `globalStore`. Populated by every commit that
   * staged a write (`memory/recordCommit.ts · recordCommit`), with the already-computed redacted patches.
   * Only exists when the run's policy keeps a mirror (`RunPolicy.mirror` —
   * `FlowChartExecutor` sets it when a `RedactionPolicy` is configured).
   * Otherwise undefined and zero cost.
   *
   * Read via `getSnapshot({ redact: true })`.
   */
  public redactedStore?: SharedMemory;
  public rootStageContext: StageContext;
  public executionHistory: EventLog;
  /** The run's sink, when this runtime's log writes to one — handed on to every mount (`recordFor`). */
  private recordSink?: RecordSink;
  /** Original root for getSnapshot() — set before resume changes rootStageContext. */
  private _snapshotRoot?: StageContext;
  private _initialState: unknown;
  readonly historyOmitted: boolean;
  private _defaultValues: unknown;
  /** The run's policy (`memory/runPolicy.ts`) — installed on the root frame;
   *  its `commitValues` and `writeProvenance` are the snapshot discriminants. */
  private policy: RunPolicy;

  /** Memoized frozen fold base — see {@link RuntimeSnapshot.initialState}. */
  private _foldBase?: Record<string, unknown>;

  /**
   * @param policy The run's policy (`runPolicy.ts`, F5) — the four dials, the
   *   redaction rule, the mirror flag. Installed on the root frame here, so
   *   the FIRST commit (a subflow's seed, `history[0]`) already runs under it;
   *   every frame after inherits the same reference. Default: every dial at
   *   its default, no rule, no mirror.
   */
  constructor(
    rootName: string,
    rootId: string,
    defaultValues?: unknown,
    initialState?: unknown,
    policy: RunPolicy = DEFAULT_RUN_POLICY,
    record?: RuntimeRecord,
    source?: {
      readonly runId: string;
      readonly address?: LogAddress;
      readonly unavailable?: SourceLimitation;
      readonly historyOmitted?: boolean;
      readonly explain?: ExplainCapture;
    },
  ) {
    this.historyOmitted = source?.historyOmitted === true;
    this._initialState = initialState;
    this._defaultValues = defaultValues;
    this.globalStore = new SharedMemory(defaultValues, initialState);
    const capture = subflowCaptureFor(policy);
    // The event log's fold base must be the SAME state the store starts from
    // — `initialContext` merged with `defaultValuesForContext`, which is what
    // `SharedMemory` computed above. Seeding the log from `initialState` alone
    // left `defaultValues` out of every replay, so a fold could not reproduce
    // the state a stage actually saw. `getState()` is the live context; the
    // EventLog constructor clones it, so the base stays detached.
    const sourceAddress =
      (policy.readSources || policy.captureOutputHandoff || capture) && source
        ? source.address ?? { logRunId: source.runId, drillPath: [] }
        : undefined;
    const unsupportedSourceAddress =
      policy.readSources && source?.address && !source.unavailable && !supportsNativeSourceAddress(source.address);
    // A sink needs an object base. Unsupported roots keep their original native
    // log/source behavior and supply no handoff bundle instead of changing the run.
    const canTap = (policy.captureOutputHandoff || capture) && sourceAddress && hasSourceSinkBase(this.globalStore);
    if (
      policy.readSources &&
      source?.runId &&
      sourceAddress &&
      !source.unavailable &&
      !unsupportedSourceAddress &&
      (!record ||
        (record.address.logRunId === sourceAddress.logRunId &&
          record.address.drillPath.length === sourceAddress.drillPath.length &&
          record.address.drillPath.every((part, index) => part === sourceAddress.drillPath[index]) &&
          hasSourceSinkBase(this.globalStore)))
    ) {
      // The record owns origin selection, first-touch fallback, staging and commit admission.
      // Open once, before any frame exists. Constructor/clone errors keep their original identity.
      const appSink = record ? sourceSink(record) : undefined;
      if (canTap) this.handoffCommitTap = createCommitTap(appSink);
      const sink = this.handoffCommitTap?.sink ?? appSink;
      const book = createReadSourceRecord(this.globalStore, sourceAddress, {
        ...(typeof policy.readSources === 'object' ? policy.readSources : {}),
        ...(sink && { sink }),
        collects: record?.collects,
      });
      this.executionHistory = book.log;
      this.readSources = new EngineReadSourceCapture(
        source.runId,
        book,
        source.historyOmitted ? 'source-history-not-included' : undefined,
      );
    } else {
      if (canTap) this.handoffCommitTap = createCommitTap(record?.sink);
      const tappedRecord = this.handoffCommitTap
        ? { ...record, address: record?.address ?? sourceAddress!, sink: this.handoffCommitTap.sink }
        : record;
      this.executionHistory = openLog(this.globalStore.getState(), tappedRecord);
      // A handoff names two real local logs, even when exact scalar-source capture is off.
      if ((policy.captureOutputHandoff || capture) && sourceAddress && !this.executionHistory.address)
        this.executionHistory.bindAddress(sourceAddress.logRunId, sourceAddress.drillPath);
      // The log supports addresses outside the source wire envelope. Preserve its real identity,
      // including before a seed commit and for deeper mounts; never shorten or relabel it as a root.
      if (unsupportedSourceAddress && sourceAddress)
        this.executionHistory.bindAddress(sourceAddress.logRunId, sourceAddress.drillPath);
      if (policy.readSources && source?.runId) {
        this.readSources = new EngineReadSourceCapture(
          source.runId,
          undefined,
          source.unavailable ?? (unsupportedSourceAddress ? 'source-address-unsupported' : 'sink-source-unsupported'),
        );
        if (source.historyOmitted) this.readSources.limit('source-history-not-included');
      }
    }
    if (record && this.executionHistory.address !== undefined) this.recordSink = record.sink;
    this.policy = policy;
    this.rootStageContext = this.newRoot(rootName, rootId);
    if (source?.explain && source.address) {
      if (!this.executionHistory.address)
        this.executionHistory.bindAddress(source.address.logRunId, source.address.drillPath);
      this.beginCapture(source.runId, false).explanation = source.explain.fork();
    }
  }

  /**
   * A fresh root frame for this runtime — `globalStore`, `executionHistory`,
   * the run's policy and (when kept) the mirror. Also how `SubflowExecutor`
   * replaces a subflow's seed frame with the frame its first stage runs on.
   */
  newRoot(name: string, id: string): StageContext {
    const root = new StageContext('', name, id, this.globalStore, '', this.executionHistory);
    this.installPolicy(root);
    return root;
  }

  /**
   * Install the run's policy on the CURRENT root frame — a same-executor
   * resume, whose continuation root (`leaf.createNext`) is advanced before
   * the executor builds this leg's policy (a fresh rule per leg). Every
   * descendant takes the reference from there.
   */
  usePolicy(policy: RunPolicy): void {
    if (policy.nestedReadTracking !== this.policy.nestedReadTracking)
      throw new TypeError('nestedReadTracking cannot change within a log; start a new executor');
    this.policy = policy;
    this.installPolicy(this.rootStageContext);
  }

  /**
   * The policy on `root`, and the mirror store when the policy keeps one.
   * The mirror is a SERVED surface, so its seed must already be the policy's
   * view of the starting state: a policy key that arrives by `initialContext`
   * / `defaultValuesForContext` (or, on a cross-executor resume, by the
   * checkpoint's `sharedState`) and is never re-written would otherwise sit
   * in `getSnapshot({ redact: true })` in plaintext — so the seed is scrubbed
   * with the LOG's placeholder, the same string the redacted patches carry.
   * Created once per runtime (a subflow's runtime keeps its own; its seed is
   * empty — the input arrives as a commit).
   */
  private installPolicy(root: StageContext): void {
    root.usePolicy(this.policy);
    root.readSources = this.readSources;
    if (this.capture?.explanation) root.capture = this.capture;
    if (!this.policy.mirror) return;
    if (!this.redactedStore) {
      const rule = this.policy.redaction;
      this.redactedStore = new SharedMemory(
        rule ? rule.retainState(this._defaultValues, LOG_PLACEHOLDER) : this._defaultValues,
        rule ? rule.retainState(this._initialState, LOG_PLACEHOLDER) : this._initialState,
      );
    }
    root.useRedactedMirror(this.redactedStore);
  }

  /** Preserve the current rootStageContext for snapshots before changing it for resume. */
  preserveSnapshotRoot(): void {
    if (!this._snapshotRoot) {
      this._snapshotRoot = this.rootStageContext;
    }
  }

  /**
   * The frozen, detached fold base served as {@link RuntimeSnapshot.initialState}.
   * Computed once (the base never changes after construction) and shared —
   * safe because it is deeply frozen, so no holder can mutate it or reach the
   * engine through it; a base holding a Date, Map, buffer … (what freezing
   * cannot seal) is served by the public snapshot as a copy of its open paths
   * (`runner/snapshot.ts · servedSnapshot`, `foottrace · serveRecord`,
   * 9.44.2).
   */
  private getFoldBase(): Record<string, unknown> {
    if (!this._foldBase) {
      const base = this.executionHistory.getInitialState();
      this._foldBase = freezeRecord(base && typeof base === 'object' ? base : {}) as Record<string, unknown>;
    }
    return this._foldBase;
  }

  /**
   * Where a mount's log writes (10.1, P6): the same sink, at this log's address plus the mount's `runtimeStageId`
   * (`drillPath: [...parent, mount]`, the address law `RuntimeSnapshot.logAddress` states). Absent when this log
   * writes to no sink — a mount of a plain log is plain too.
   */
  recordFor(mountRuntimeStageId: string, meta?: Meta): RuntimeRecord | undefined {
    const address = childLogAddress(this.executionHistory.address, mountRuntimeStageId);
    if (this.recordSink === undefined || address === undefined) return undefined;
    return {
      sink: this.recordSink,
      address,
      ...(meta === undefined ? {} : { meta }),
    };
  }

  /** Tell the sink this runtime's log ended. Nothing happens without a sink; never throws. */
  closeRecord(outcome: LogOutcome, meta?: Meta): void {
    // A child closes even without a sink. Retire its own book before late callbacks can extend its evidence.
    this.readSources?.seal(this.executionHistory.length);
    this.executionHistory.close(outcome, meta);
  }

  /** Note something beside this runtime's log, in its sink (a resumed leg). Nothing without a sink; never throws. */
  noteRecord(kind: string, data: Meta): void {
    this.executionHistory.note(kind, data);
  }

  getPipelines(): string[] {
    const state = this.globalStore.getState();
    return state.pipelines ? Object.keys(state.pipelines as Record<string, unknown>) : [];
  }

  setRootObject(path: string[], key: string, value: unknown) {
    this.rootStageContext.setObject(path, key, value);
  }

  /**
   * Return the runtime snapshot.
   *
   * @param options.redact  When `true`, returns `sharedState` from the
   *   parallel redacted mirror (if one was enabled). This is the safe view
   *   for sharing traces externally — paste into a viewer, ship to support,
   *   etc. When the mirror was never enabled, falls back to raw `globalStore`.
   *
   *   Default `false` preserves the runtime view — necessary for pause /
   *   resume (resumption must replay against the real values, not
   *   '[REDACTED]').
   *
   * The commit log and stage tree use the same retention rules in both views.
   * The stage tree checks the current rule for previously unset reads.
   *
   * `initialState` is the actual frozen pre-run base, served through the same
   * state rule as the mirror seed and a record sink's opened entry. Read the
   * live rule on every export: a later whole-key or inherited field mark must
   * also cover an earlier seed. Never reconstruct the base from final state.
   *
   * Returns `Omit<RuntimeSnapshot, 'runId' | 'correlation'>`: the runtime is the memory
   * container and doesn't know which run it serves — `runId` is per-run
   * executor state, stamped by `FlowchartTraverser.getSnapshot()` (which
   * owns the run's id and already stamps it on every event). Subflows'
   * nested runtimes deliberately have NO runId of their own (a subflow is
   * part of the parent's logical run). `correlation` is the traverser's for
   * the same reason.
   */
  getSnapshot(options?: { redact?: boolean }): Omit<RuntimeSnapshot, 'runId' | 'correlation'> {
    const snapshotRoot = this._snapshotRoot ?? this.rootStageContext;
    const useRedacted = options?.redact === true && this.redactedStore !== undefined;
    const base = this.getFoldBase();
    const retainedBase =
      useRedacted && this.policy.redaction ? this.policy.redaction.retainState(base, LOG_PLACEHOLDER) : base;
    const collections = subflowCaptureFor(this.policy)?.view(this, options?.redact === true);
    return {
      sharedState: useRedacted ? this.redactedStore!.getState() : this.globalStore.getState(),
      executionTree: snapshotRoot.getSnapshot(this.policy.redaction),
      // The original base is already frozen. Only a scrubbed copy needs to
      // enter the record's freeze/serve law; the raw fast path is unchanged.
      initialState: retainedBase === base ? base : freezeRecord(retainedBase),
      // DETACHED: the engine keeps its live EventLog; the snapshot gets a
      // frozen array of its own (`recorded()` builds a new one). Serving the
      // internal array aliased it, so a snapshot taken mid-run kept growing
      // under its holder and a consumer could splice the engine's own history.
      // The bundles in it are the log's own, frozen at `EventLog · record`
      // (F3). The public snapshot serves them (`runner/snapshot.ts ·
      // servedSnapshot`, 9.44.2); this one is also the engine's own — a
      // subflow mount takes it once per mount — so the run path serves nothing.
      commitLog: Object.freeze(this.executionHistory.recorded()) as CommitBundle[],
      ...(this.executionHistory.address === undefined ? {} : { logAddress: this.executionHistory.address }),
      commitValues: this.policy.commitValues,
      writeProvenance: this.policy.writeProvenance,
      ...(this.policy.captureOutputHandoff && { captureOutputHandoff: true as const }),
      ...(collections && { fanoutCollections: collections }),
      ...(this.policy.nestedReadTracking && { nestedReadTracking: true as const }),
      ...(this.readSources && {
        readSources: this.readSources.snapshot(this.executionHistory.length, options?.redact === true),
      }),
    };
  }
}

/**
 * The runtime's log: with a record, the log that writes to the sink as it lands. A base the sink cannot carry (it
 * must be a plain object) is the sink's loss, never the run's — the log is then the plain one, and the loss is
 * reported to the sink like any other (`RecordSink.onFailure`), so the run's accounting names it.
 */
function openLog(base: Record<string, unknown>, record: RuntimeRecord | undefined): EventLog {
  if (record === undefined) return new EventLog(base);
  try {
    return new EventLog(base, record);
  } catch (error) {
    try {
      record.sink.onFailure?.({
        entry: { kind: 'opened', address: record.address, at: Date.now(), initialState: {} },
        error,
      });
    } catch {
      // The run's own sink isolates its listener; an app's raw adapter here is told once, best effort.
    }
    return new EventLog(base);
  }
}

/** Preserve the engine's opened metadata through the record's public source-writer sink port. */
function sourceSink(record: RuntimeRecord): RecordSink {
  return {
    opened: (entry) => {
      let meta: Meta | undefined;
      try {
        // The native writer accepts a sink but not opened meta. Engine-owned meta still leaves as a copy.
        meta = record.meta === undefined ? undefined : structuredClone(record.meta);
      } catch (error) {
        try {
          settleOnce(
            record.sink.onFailure?.({ entry: { ...entry, kind: 'opened' }, error }),
            () => undefined,
            () => undefined,
          );
        } catch {
          // Reporting a metadata loss never suppresses the structural opened entry.
        }
      }
      // Keep adapter throws/rejections on the normal EventLog/RunRecord accounting path, exactly once.
      return record.sink.opened({ ...entry, ...(meta !== undefined && { meta }) });
    },
    commit: (entry) => record.sink.commit(entry),
    note: (entry) => record.sink.note(entry),
    closed: (entry) => record.sink.closed(entry),
    onFailure: (failure) => record.sink.onFailure?.(failure),
  };
}

/** Eligibility only: unsupported roots keep openLog's existing native refusal/report/fallback path. */
function hasSourceSinkBase(state: SharedMemory): boolean {
  const base = state.getState();
  return typeof base === 'object' && base !== null && !Array.isArray(base);
}
